# Background server state: start.ps1 (the supervisor) records what it runs here.
# ---------------------------------------------------------------------------
$script:StateFile = Join-Path $PSScriptRoot "state.json"
$script:StopFlag = Join-Path $PSScriptRoot "stop.flag"
$script:TaskName = "Lab CRM Server"

function Get-ProcStart([int]$ProcessId) {
    try { return (Get-Process -Id $ProcessId -ErrorAction Stop).StartTime.ToUniversalTime().ToString("o") } catch { return $null }
}

function Test-ProcAlive($ProcessId, $StartedAt) {
    if (-not $ProcessId) { return $false }
    $actual = Get-ProcStart ([int]$ProcessId)
    if (-not $actual) { return $false }
    return (-not $StartedAt) -or ($actual -eq $StartedAt)
}

function Save-State($State) {
    [IO.File]::WriteAllText($script:StateFile, ($State | ConvertTo-Json -Depth 4), (New-Object Text.UTF8Encoding($false)))
}

function Read-State {
    if (-not (Test-Path $script:StateFile)) { return $null }
    try { return (Get-Content -Path $script:StateFile -Raw -Encoding UTF8 | ConvertFrom-Json) } catch { return $null }
}

function Get-ServerState {
    $state = Read-State
    if ($state -and (Test-ProcAlive $state.supervisorPid $state.supervisorStart)) { return $state }
    return $null
}

function ConvertTo-Utc($Value) {
    if ($Value -is [datetime]) { return $Value.ToUniversalTime() }
    return [DateTimeOffset]::Parse([string]$Value, [Globalization.CultureInfo]::InvariantCulture).UtcDateTime
}

function Start-Detached([string]$CommandLine, [string]$WorkDir) {
    $startup = New-CimInstance -ClassName Win32_ProcessStartup -ClientOnly -Property @{ ShowWindow = [uint16]0 }
    $result = Invoke-CimMethod -ClassName Win32_Process -MethodName Create -Arguments @{
        CommandLine = $CommandLine; CurrentDirectory = $WorkDir; ProcessStartupInformation = $startup
    }
    if ($result.ReturnValue -ne 0) { throw "Windows не смог запустить фоновый процесс (код $($result.ReturnValue))." }
    return [int]$result.ProcessId
}

function Invoke-Native([scriptblock]$Command) {
    $previous = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try {
        $output = @(& $Command 2>&1 | ForEach-Object { "$_" })
        return [pscustomobject]@{ ExitCode = $LASTEXITCODE; Output = $output }
    }
    finally { $ErrorActionPreference = $previous }
}

function Stop-ProcessTree($ProcessId) {
    if ($ProcessId) { [void](Invoke-Native { & taskkill /PID $ProcessId /T /F }) }
}

function Stop-Server([int]$GraceSeconds = 15) {
    $state = Read-State
    if (-not $state) { return }

    if (Test-ProcAlive $state.supervisorPid $state.supervisorStart) {
        [IO.File]::WriteAllText($script:StopFlag, "stop")
        $deadline = (Get-Date).AddSeconds($GraceSeconds)
        while ((Get-Date) -lt $deadline -and (Test-ProcAlive $state.supervisorPid $state.supervisorStart)) { Start-Sleep -Milliseconds 300 }
        if (Test-ProcAlive $state.supervisorPid $state.supervisorStart) {
            Stop-ScheduledTask -TaskName $script:TaskName -ErrorAction SilentlyContinue
            Stop-ProcessTree $state.supervisorPid
        }
    }
    if (Test-ProcAlive $state.appPid $state.appStart) { Stop-ProcessTree $state.appPid }
    Remove-Item $script:StopFlag, $script:StateFile -ErrorAction SilentlyContinue
}

function Get-AutostartTask { return Get-ScheduledTask -TaskName $script:TaskName -ErrorAction SilentlyContinue }

function Format-Size([double]$Bytes) {
    if ($Bytes -ge 1GB) { return ("{0:N1} ГБ" -f ($Bytes / 1GB)) }
    if ($Bytes -ge 1MB) { return ("{0:N1} МБ" -f ($Bytes / 1MB)) }
    if ($Bytes -ge 1KB) { return ("{0:N0} КБ" -f ($Bytes / 1KB)) }
    return ("{0:N0} Б" -f $Bytes)
}

function Get-FolderSize([string]$Path) {
    if (-not (Test-Path $Path)) { return 0 }
    $sum = (Get-ChildItem -Path $Path -Recurse -File -Force -ErrorAction SilentlyContinue | Measure-Object -Property Length -Sum).Sum
    if ($sum) { return $sum }
    return 0
}

# ---------------------------------------------------------------------------
# Git: обновление - git pull в своей папке (без сборки/миграций, их тут просто нет).
# ---------------------------------------------------------------------------
function Invoke-Git {
    $git = Find-Executable "git"
    if (-not $git) { throw "git не установлен (winget install Git.Git)." }
    $ErrorActionPreference = "Continue"
    $lines = & $git -c core.quotepath=off -c safe.directory=* -C $script:Root @args 2>&1 | ForEach-Object { "$_" }
    $script:GitExit = $LASTEXITCODE
    return @($lines)
}

function Get-GitInfo([switch]$NoFetch) {
    $info = [ordered]@{
        gitInstalled = [bool](Find-Executable "git"); isRepo = $false; hasCommits = $false; branch = ""; upstream = ""; remote = ""
        head = ""; headDate = ""; headMessage = ""; behind = 0; ahead = 0; dirty = 0; commits = @(); error = ""
    }
    if (-not $info.gitInstalled) { return $info }
    if (-not (Test-Path (Join-Path $script:Root ".git"))) { return $info }
    $info.isRepo = $true

    [void](Invoke-Git rev-parse --verify --quiet HEAD)
    $info.hasCommits = ($script:GitExit -eq 0)
    $remote = Invoke-Git remote get-url origin
    if ($script:GitExit -eq 0) { $info.remote = "$($remote | Select-Object -First 1)" }
    if (-not $info.hasCommits) { return $info }

    $branch = Invoke-Git rev-parse --abbrev-ref HEAD
    if ($script:GitExit -eq 0) { $info.branch = "$($branch | Select-Object -First 1)" }
    $log = @(Invoke-Git log -1 "--format=%h|%cd|%s" "--date=format:%d.%m.%Y %H:%M")
    if ($script:GitExit -eq 0 -and $log.Count -gt 0) {
        $parts = "$($log[0])".Split("|", 3)
        if ($parts.Count -eq 3) { $info.head = $parts[0]; $info.headDate = $parts[1]; $info.headMessage = $parts[2] }
    }
    $info.dirty = @(Invoke-Git status --porcelain -uno | Where-Object { $_ }).Count

    if (-not $NoFetch -and $info.remote) {
        $fetch = Invoke-Git fetch --quiet
        if ($script:GitExit -ne 0) { $info.error = ("$($fetch -join ' ')").Trim() }
    }
    $upstream = Invoke-Git rev-parse --abbrev-ref --symbolic-full-name "@{u}"
    if ($script:GitExit -eq 0) {
        $info.upstream = "$($upstream | Select-Object -First 1)"
        $behind = Invoke-Git rev-list --count "HEAD..@{u}"
        if ($script:GitExit -eq 0) { $info.behind = [int]"$($behind | Select-Object -First 1)" }
        $ahead = Invoke-Git rev-list --count "@{u}..HEAD"
        if ($script:GitExit -eq 0) { $info.ahead = [int]"$($ahead | Select-Object -First 1)" }
        $info.commits = @(Invoke-Git log "HEAD..@{u}" "--format=%h  %s" -n 30 | Where-Object { $_ })
    }
    return $info
}
